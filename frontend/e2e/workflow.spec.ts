import { test, expect } from '@playwright/test'
import { addDays, mondayOf, todayShanghai } from '../src/dates'

test('管理员与普通用户完成周报流程', async ({ page, context }) => {
  const errors: string[] = []
  const usernames: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (request.url().endsWith('/api/auth/login')) usernames.push(request.postDataJSON().username) })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '登录周报' })).toBeVisible()
  await page.getByLabel('用户名').fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('e2e-password-123')
  await page.getByRole('button', { name: /进入工作台/ }).click()
  await expect(page.getByRole('heading', { name: '本周工作' })).toBeVisible()
  await page.getByRole('button', { name: /用户管理/ }).click()
  await expect(page.getByRole('heading', { name: '用户管理' })).toBeVisible()
  await page.getByRole('button', { name: '退出登录' }).click()
  await expect(page).toHaveURL(/\/login$/)
  await page.getByLabel('用户名').fill('alice')
  await expect(page.getByLabel('用户名')).toHaveValue('alice')
  await page.getByLabel('密码', { exact: true }).fill('e2e-password-123')
  const aliceLogin = page.waitForResponse(response => response.url().endsWith('/api/auth/login'))
  await page.getByRole('button', { name: /进入工作台/ }).click()
  const secondLogin = await aliceLogin
  expect(usernames).toEqual(['admin', 'alice'])
  expect(secondLogin.request().postDataJSON().username).toBe('alice')
  expect((await secondLogin.json()).user.username).toBe('alice')
  await expect(page.locator('.identity')).toContainText('alice')
  await expect(page.getByRole('button', { name: /用户管理/ })).toHaveCount(0)

  await page.getByRole('button', { name: /任务类型/ }).click()
  await page.getByPlaceholder('例如：产品开发').fill('研发')
  await page.getByRole('button', { name: '新增类型' }).click()
  await expect(page.getByRole('textbox', { name: '任务类型 研发' })).toBeVisible()
  await page.getByRole('button', { name: /本周工作/ }).click()
  await page.getByRole('button', { name: '新增任务' }).click()
  const first = page.locator('.task-row').first()
  await first.getByRole('combobox').first().selectOption('研发')
  await first.getByRole('textbox', { name: '任务大类' }).fill('平台升级')
  await first.getByPlaceholder('写下这项工作…').fill('完成接口联调')
  await first.getByRole('combobox').nth(1).selectOption('90%')
  await first.getByRole('button', { name: '周一未选中' }).click()
  await expect(page.getByText('✓ 已保存')).toBeVisible()
  await expect(page.locator('.calendar-day.current')).toHaveCount(7)
  const markedSunday = addDays((await page.locator('.calendar-caption').textContent())!.slice(0, 10), 6)
  await expect(page.getByRole('button', { name: `${markedSunday}，选择该周，已有任务` })).toBeVisible()
  await first.getByRole('button', { name: '复制一行' }).click()
  await expect(page.locator('.task-row')).toHaveCount(2)
  await page.locator('.task-row').nth(1).getByRole('button', { name: '删除' }).click()
  await page.getByRole('button', { name: '取消' }).click()
  await expect(page.locator('.task-row')).toHaveCount(2)
  await page.locator('.task-row').nth(1).getByRole('button', { name: '删除' }).click()
  await page.getByRole('button', { name: '确认删除' }).click()
  await expect(page.locator('.task-row')).toHaveCount(1)
  await page.reload()
  await expect(page.locator('.task-row').first().getByPlaceholder('写下这项工作…')).toHaveValue('完成接口联调')
  const currentWeek = (await page.locator('.calendar-caption').textContent())!.slice(0, 10)
  const previousWeek = addDays(currentWeek, -7)
  await page.getByRole('button', { name: `${previousWeek}，选择该周` }).click()
  await page.getByRole('button', { name: '新增任务' }).click()
  await page.locator('.task-row').first().getByPlaceholder('写下这项工作…').fill('上周遗留工作')
  await expect(page.getByText('✓ 已保存')).toBeVisible()
  await page.getByRole('button', { name: `${currentWeek}，选择该周` }).click()
  await page.getByRole('button', { name: /复制上周未完成/ }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: '取消' }).click()
  await expect(page.locator('.task-row')).toHaveCount(1)
  await page.getByRole('button', { name: /复制上周未完成/ }).click()
  await page.getByRole('button', { name: '新增', exact: true }).click()
  await expect(page.locator('.task-row')).toHaveCount(2)
  await expect(page.locator('.task-row').nth(1).getByPlaceholder('写下这项工作…')).toHaveValue('上周遗留工作')
  await page.getByRole('button', { name: /复制上周未完成/ }).click()
  await page.getByRole('button', { name: '覆盖' }).click()
  await expect(page.locator('.task-row')).toHaveCount(1)
  await expect(page.locator('.task-row').first().getByPlaceholder('写下这项工作…')).toHaveValue('上周遗留工作')
  await expect(page.locator('.task-row').first().getByRole('button', { name: '周一未选中' })).toBeVisible()
  const sibling = await context.newPage()
  await sibling.goto('/work')
  await sibling.locator('.task-row').first().getByPlaceholder('补充说明…').fill('另一个标签页修改')
  await expect(sibling.getByText('✓ 已保存')).toBeVisible()
  await page.locator('.task-row').first().getByPlaceholder('补充说明…').fill('当前标签页修改')
  await expect(page.getByText('! 内容冲突')).toBeVisible()
  await page.getByRole('button', { name: '用当前修改重试' }).click()
  await expect(page.getByText('✓ 已保存')).toBeVisible()
  await sibling.reload()
  await expect(sibling.locator('.task-row').first().getByPlaceholder('补充说明…')).toHaveValue('当前标签页修改')
  await sibling.close()
  await page.screenshot({ path: 'test-results/work-desktop.png', fullPage: true })
  await page.getByRole('button', { name: /周报汇总/ }).click()
  await expect(page.getByRole('tab', { name: '管理员' })).toHaveCount(0)
  await page.getByRole('tab', { name: '小王' }).click()
  await expect(page.getByText('上周遗留工作')).toBeVisible()
  await expect(page.getByRole('button', { name: '复制一行' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '删除', exact: true })).toHaveCount(0)
  for (const width of [320, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 800 })
    if (width <= 768) await page.getByRole('button', { name: '打开或关闭导航' }).click()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
    if (width === 320) await page.screenshot({ path: 'test-results/report-mobile.png', fullPage: true })
  }
  await page.getByRole('button', { name: '＋ 新增会议记录' }).click()
  await page.getByRole('dialog', { name: '新增会议记录' }).getByLabel('会议类型').fill('例会')
  await page.getByRole('dialog', { name: '新增会议记录' }).getByLabel('会议内容').fill('项目同步')
  await page.getByRole('dialog', { name: '新增会议记录' }).getByLabel('是否需要跟踪完成情况').selectOption('true')
  await page.getByRole('button', { name: '＋ 添加任务' }).click()
  await page.getByRole('dialog', { name: '新增会议记录' }).getByLabel('任务名称').fill('完成联调')
  await page.getByRole('dialog', { name: '新增会议记录' }).getByLabel('任务状态').selectOption('未完成')
  await page.getByRole('button', { name: '保存会议记录' }).click()
  await page.getByRole('button', { name: /会议记录/ }).first().click()
  await expect(page.getByText('项目同步')).toBeVisible()
  await expect(page.getByText('完成联调')).toBeVisible()
  await page.getByRole('button', { name: '退出登录' }).click()
  await expect(page).toHaveURL(/\/login$/)
  await page.getByLabel('用户名').fill('bob')
  await page.getByLabel('密码', { exact: true }).fill('e2e-password-123')
  await page.getByRole('button', { name: /进入工作台/ }).click()
  await expect(page.locator('.identity')).toContainText('bob')
  await expect(page.getByText('本周还没有任务。')).toBeVisible()
  await page.getByRole('button', { name: /周报汇总/ }).click()
  await page.getByRole('tab', { name: '小王' }).click()
  await expect(page.getByText('上周遗留工作')).toBeVisible()
  expect(errors).toEqual([])
})

test('窄屏无页面横向溢出', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 700 })
  await page.goto('/login')
  await expect(page.getByRole('heading', { name: '登录周报' })).toBeVisible()
  await page.getByRole('button', { name: /进入工作台/ }).click()
  expect(await page.getByLabel('用户名').evaluate(input => (input as HTMLInputElement).validationMessage)).toBe('请填写此项。')
  await page.getByLabel('用户名').fill('nobody')
  await page.getByLabel('密码', { exact: true }).fill('wrong-password')
  await page.getByRole('button', { name: /进入工作台/ }).click()
  await expect(page.getByRole('alert')).toContainText('用户名或密码错误')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
})

test('新用户必须改密后才能维护会议记录', async ({ page }) => {
  const username = `fresh${Date.now()}`
  const content = `首次登录后创建${username}`
  const editedContent = `已编辑的会议记录${username}`
  let passwordRequests = 0
  page.on('request', request => { if (request.url().endsWith('/api/auth/password')) passwordRequests++ })
  await page.goto('/login')
  await page.getByLabel('用户名').fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('e2e-password-123')
  await page.getByRole('button', { name: /进入工作台/ }).click()
  await page.getByRole('button', { name: /用户管理/ }).click()
  await page.getByRole('textbox', { name: '用户名' }).first().fill(username)
  await page.getByRole('textbox', { name: '显示姓名' }).fill('首次登录用户')
  await page.getByLabel('初始密码').fill('123456')
  await page.getByRole('button', { name: '创建用户' }).click()
  await expect(page.getByText(username, { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '退出登录' }).click()
  await expect(page).toHaveURL(/\/login$/)
  await page.getByLabel('用户名').fill(username)
  await page.getByLabel('密码', { exact: true }).fill('123456')
  await page.getByRole('button', { name: /进入工作台/ }).click()
  await expect(page.getByRole('heading', { name: '首次登录，请修改初始密码' })).toBeVisible()
  await page.goto('/work')
  await expect(page).toHaveURL(/\/password$/)
  await page.getByLabel('当前密码').fill('123456')
  await page.getByLabel('新密码（至少 6 位）').fill('123456')
  await page.getByLabel('确认新密码').fill('123456')
  await page.getByRole('button', { name: '更新密码' }).click()
  await expect(page.getByRole('alert')).toContainText('新密码不能与当前密码相同')
  expect(passwordRequests).toBe(1)
  await page.getByLabel('新密码（至少 6 位）').fill('654321')
  await page.getByLabel('确认新密码').fill('abcdef')
  await page.getByRole('button', { name: '更新密码' }).click()
  await expect(page.getByRole('alert')).toContainText('两次输入的新密码不一致')
  expect(passwordRequests).toBe(1)
  await page.getByLabel('确认新密码').fill('654321')
  await page.getByRole('button', { name: '更新密码' }).click()
  await expect(page).toHaveURL(/\/login$/)
  await page.getByLabel('用户名').fill(username)
  await page.getByLabel('密码', { exact: true }).fill('654321')
  await page.getByRole('button', { name: /进入工作台/ }).click()
  await expect(page.getByRole('heading', { name: '本周工作' })).toBeVisible()
  await page.getByRole('button', { name: /会议记录/ }).click()
  await page.getByRole('button', { name: '＋ 新增会议记录' }).click()
  const dialog = page.getByRole('dialog', { name: '新增会议记录' })
  await dialog.getByLabel('会议类型').fill('专项会')
  await dialog.getByLabel('会议内容').fill(content)
  await dialog.getByLabel('是否需要跟踪完成情况').selectOption('true')
  await dialog.getByRole('button', { name: '＋ 添加任务' }).click()
  await dialog.getByLabel('任务名称').fill('检查结果')
  await dialog.getByLabel('任务状态').selectOption('未完成')
  await dialog.getByRole('button', { name: '保存会议记录' }).click()
  await expect(dialog).toHaveCount(0)
  await page.getByLabel('任务状态').selectOption('未完成')
  await page.getByRole('button', { name: '查询' }).click()
  const card = page.locator('.meeting-card').filter({ hasText: content })
  await expect(card).toBeVisible()
  await card.getByRole('button', { name: '编辑' }).click()
  await page.getByRole('dialog', { name: '编辑会议记录' }).getByLabel('会议内容').fill(editedContent)
  await page.getByRole('button', { name: '保存会议记录' }).click()
  const edited = page.locator('.meeting-card').filter({ hasText: editedContent })
  await expect(edited).toBeVisible()
  page.once('dialog', async prompt => { await prompt.accept() })
  await edited.getByRole('button', { name: '删除' }).click()
  await expect(page.getByText(editedContent)).toHaveCount(0)
})

test('月历回到本周会重查对应页面', async ({ page }) => {
  const today = todayShanghai()
  const currentWeek = mondayOf(today)
  const monthLabel = `${today.slice(0, 4)} / ${today.slice(5, 7)}`
  await page.goto('/login')
  await page.getByLabel('用户名').fill('alice')
  await page.getByLabel('密码', { exact: true }).fill('e2e-password-123')
  await page.getByRole('button', { name: /进入工作台/ }).click()
  await expect(page.getByRole('heading', { name: '本周工作' })).toBeVisible()
  await page.getByRole('button', { name: '下个月' }).click()
  const back = page.getByRole('button', { name: '回到本周' })
  await expect(back).toHaveAttribute('title', '回到本周')
  const weekQuery = page.waitForResponse(response => response.url().endsWith(`/api/weeks/${currentWeek}`) && response.request().method() === 'GET')
  const workMarks = page.waitForResponse(response => response.url().includes(`/api/calendar/marks?year=${today.slice(0, 4)}&month=${Number(today.slice(5, 7))}&scope=work`))
  await back.click()
  expect((await weekQuery).status()).toBe(200)
  expect((await workMarks).status()).toBe(200)
  await expect(page.locator('.calendar-head strong')).toHaveText(monthLabel)
  await expect(page.locator('.calendar-caption')).toContainText(currentWeek)
  await page.getByRole('button', { name: /周报汇总/ }).click()
  await page.getByRole('button', { name: '下个月' }).click()
  const reportQuery = page.waitForResponse(response => response.url().endsWith(`/api/reports/${currentWeek}`))
  const reportMarks = page.waitForResponse(response => response.url().includes(`/api/calendar/marks?year=${today.slice(0, 4)}&month=${Number(today.slice(5, 7))}&scope=reports`))
  await page.getByRole('button', { name: '回到本周' }).click()
  expect((await reportQuery).status()).toBe(200)
  expect((await reportMarks).status()).toBe(200)
  await expect(page.locator('.calendar-head strong')).toHaveText(monthLabel)
  await page.setViewportSize({ width: 320, height: 700 })
  await page.getByRole('button', { name: '打开或关闭导航' }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
})
